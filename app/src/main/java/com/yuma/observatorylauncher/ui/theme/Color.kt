package com.yuma.observatorylauncher.ui.theme

import androidx.compose.ui.graphics.Color

/**
 * observatory.css のトークンをそのまま移植した唯一の正本。
 * 個々の画面はここを経由せず色を直書きしない。
 */
object ObservatoryColors {
    val Ground = Color(0xFF22303C)   // 鉄紺 — 地の色
    val Ember = Color(0xFFE4572E)    // 燠火 — 装飾・面積比12%側。ground上の本文には使わない(3.64:1でAA未満)
    // ember を可読情報用に持ち上げた版。旧 #F2764C（4.80:1）は小さな字に足りず、
    // 2026/9/25 に 6.36:1 へ上げた（Faint の注記を参照）。
    val EmberText = Color(0xFFF69B7C)
    val Paper = Color(0xFFE7E4DE)    // 紙色 — ground上の本文色

    // ヘアライン・目盛り・弦材の罫線色。燠火を使わず地味に留める(§N 目盛りの規定)。
    // **これは罫のための色であって、文字に使ってはならない**——
    // ground に重ねた実効色は約2.5:1で、HIGが求める4.5:1に遠く届かない。
    val Line = Paper.copy(alpha = 0.35f)

    // 副次的な文字（見出し・注記・単位）。ground 上で 8.13:1（2026/9/25 に 0.72→0.85）。
    val Muted = Paper.copy(alpha = 0.85f)
    val LineStrong = Paper.copy(alpha = 0.55f)

    /**
     * 小さく置くが、**読ませる**字。名札・単位・目盛りの数字。
     *
     * ## ⚠️ 0.30 から 0.60 へ上げた（2026/9/1）
     *
     * > 「グレー文字の小さいのが視認性悪い。太くするだけではダサくなる」（本人）
     *
     * 直し方は太さでも大きさでもなく、**濃さ**だった。実測すると——
     *
     * | 不透明度 | 地(#22303C)に対する比 | 判定 |
     * | --- | --- | --- |
     * | 0.30 | **2.30:1** | 不可 |
     * | 0.55 | 4.35:1 | 大きな字だけ可 |
     * | **0.60** | **4.87:1** | 小さな字でも可(AA) |
     * | 0.72 (Muted) | 6.30:1 | 可 |
     *
     * 小さな字が求める下限は 4.5:1 である。**0.30 は端から届いていなかった**
     * ——読みにくいのではなく、読めない濃さで置いていた。
     *
     * 太さを足すと確かに読めるようになるが、それは
     * **足りない濃さを線の量で埋める**やり方で、面が野暮になる。
     * 濃さで足りるなら濃さで足す。
     *
     * [Muted] との差は 0.12 しかないが、**階層は大きさが担っている**
     * （Label と Body）。色に階層まで背負わせない。
     *
     * ## ⚠️ 0.60 から 0.74 へ、さらに上げた（2026/9/25）
     *
     * > 「スマホの画面が汚れてぼやけたり、私がとても若干乱視なので
     * >  小さい文字を稀にうまく識別できなくなります」（本人）
     *
     * 4.5:1 は**澄んだ画面と正視の目**を前提にした下限である。
     * にじみは字と地の境目を混ぜ、実効の対比を下げる。
     * 小さな字は 6.5:1 以上に置く——Faint 0.74 で 6.56:1、Muted 0.85 で 8.13:1。
     *
     * 同時に、**図の罫はこの色から外した**（[Grid]）。
     * 字を濃くすると、同じ色で引いた目盛り線まで濃くなり、図が罫で埋まる。
     */
    val Faint = Paper.copy(alpha = 0.74f)

    /**
     * 図の目盛り線・分母の罫。**字には使わない。**
     *
     * もとは [Faint] で引いていた。字と罫は求める濃さが違う
     * ——字は読めるまで濃く、罫は在ることが分かる程度に薄く——ので分けた。
     */
    val Grid = Paper.copy(alpha = 0.42f)

    /**
     * **在ることは示すが、読ませはしない**もののための色。
     * 月の格子で前後の月からはみ出した日など、
     * 消すと並びが読めなくなるが、読む必要も無いもの。
     *
     * ⚠️ **文字として読ませたいものに使わない**——3.4:1 しか無い。
     * [Faint] を薄めたのではなく、[Faint] から**役割を分けて残した**方である。
     * 2026/9/25 に 0.30（2.31:1）から 0.45 へ上げた。読ませはしないが、
     * にじんだ画面で「そこに日付がある」ことまで消えては並びが読めない。
     */
    val Ghost = Paper.copy(alpha = 0.45f)

    /**
     * 暦の休みの日。**月の格子の中だけで使う。**
     *
     * ## ⚠️ 二色の体系に、三色目を入れた理由
     *
     * この体系は鉄紺と燠火の二色で通している。
     * それでも入れたのは、**日曜が赤・土曜が青という並びが、
     * 暦という道具の側の約束**だからである。
     * 濃さや太さで代えると、日本語の暦として読めなくなる。
     *
     * 逃げ道として「日曜だけ燠火」も考えたが、
     * 月の格子では燠火が既に**進行中の予定**を意味しており、
     * 一つの色に二つの意味を持たせることになる。
     *
     * だから休みの日の色は**この二つに閉じ、他の面へは持ち出さない**。
     *
     * | | 値 | 地との比 |
     * | --- | --- | --- |
     * | 日曜・祝日 | `#E6A18E` | 6.33:1 |
     * | 土曜 | `#95B5D2` | 6.31:1 |
     *
     * 燠火の文字（6.36:1）と同じ濃さに揃えてある。**赤い方が目立つ、を作らない。**
     * （2026/9/25 に三つそろって 5.2:1 前後から 6.3:1 へ上げた。）
     */
    val Sunday = Color(0xFFE6A18E)
    val Saturday = Color(0xFF95B5D2)
}
